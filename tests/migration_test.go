package bootstrap_test

import (
	"os"
	"os/exec"
	"path/filepath"
	"testing"
)

const miseBootstrapMigration = "setup/migrations/migrate-to-mise-bootstrap.sh"

// Generated APM modules survive migration from the oldest layout.
func TestLegacyAPMDataMigration(t *testing.T) {
	repo := repositoryRoot(t)
	fixtureRepo := t.TempDir()
	home := t.TempDir()
	legacySource := filepath.Join(fixtureRepo, "packages", "apm")
	currentSource := filepath.Join(fixtureRepo, "dotfiles", "ai", "apm")

	mustWriteFile(t, filepath.Join(currentSource, "apm.yml"), "dependencies: []\n", 0o644)
	mustWriteFile(t, filepath.Join(legacySource, "apm_modules", "example", "data"), "cached\n", 0o644)
	mustSymlink(t, legacySource, filepath.Join(home, ".apm"))

	runCommand(t, repo, migrationEnvironment(home), "bash", filepath.Join(repo, miseBootstrapMigration), fixtureRepo)

	assertFileContent(t, filepath.Join(home, ".apm", "apm_modules", "example", "data"), "cached\n")
	if _, err := os.Lstat(filepath.Join(legacySource, "apm_modules")); !os.IsNotExist(err) {
		t.Fatalf("legacy APM modules remain in the repository: %v", err)
	}
}

